def _rust_inventory(crate_dir: Path, example: str) -> dict:
    """Run an inventory dump example and parse its JSON stdout."""
    # ⚠⚠ `encoding="utf-8"`, and it is NOT boilerplate. `text=True` alone decodes
    # the pipe with `locale.getpreferredencoding()` — cp1252 on the Windows dev box —
    # and every byte this program emitted was ASCII (names, hex floats, sha-256
    # digests) until slice C4, so the pipe's encoding had never mattered. The science
    # census is the first non-ASCII key: it carries `—`, `⚠`, `Γ` and `CO₂` inside
    # frozen claim text. Without this the first regeneration wrote mojibake
    # (`—` -> `â€”`) INTO the frozen contract, and nothing was red — the manifest and
    # the checker agreed, because the corruption happened on the way in. It was
    # caught by predicting the diff before regenerating, which is the only reason it
    # is a note here instead of a committed contract.
    proc = subprocess.run(
        ["cargo", "run", "-q", "--example", example],
        cwd=crate_dir,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    assert proc.returncode == 0, f"cargo run {example} failed:\n{proc.stderr}"
    return json.loads(proc.stdout)


@pytest.mark.skipif(shutil.which("cargo") is None, reason="cargo not installed")
@pytest.mark.parametrize("label,crate_dir,example,manifest_name,dump_keys", _CASES)
def test_rust_inventory_equals_the_frozen_manifest(
    label: str, crate_dir: Path, example: str, manifest_name: str, dump_keys: frozenset
) -> None:
    """Rust's derived flow/aux inventory equals the committed manifest's, set for set.

    Runs wherever `cargo` is on PATH, and on the `crossport` CI job — which invokes
    `uv run pytest tests/crossport/` on the **directory**, so a new file here is
    collected rather than needing to be listed. (Checked, not inherited: this repo has
    two recorded green-by-skip incidents.)
    """
    manifest = json.loads((DOCS_DIR / manifest_name).read_text(encoding="utf-8"))
    dump = _rust_inventory(crate_dir, example)

    assert set(dump) == dump_keys, (
        f"{example} dumps {sorted(dump)}, not {sorted(dump_keys)} — see this "
        f"module's docstring before adding an axis. A new key must be classified in "
        f"the manifest's `_AUTHORITY` and must be something the reference can "
        f"honestly produce: a key whose value is really the checker's own list "
        f"travelling out and back makes this gate compare Python against Python."
    )

    # ⚠ Guard the comparison itself, not just its result. An equality against an empty
    # frozen list is a green test that has checked nothing, and the flow axis is where
    # this gate's teeth are. (The *aux* axis is legitimately empty on the station side —
    # see `test_the_station_aux_axis_is_empty_by_delegation`, which states that rather
    # than letting `[] == []` pass as evidence.)
    assert manifest["flow_set"], f"{manifest_name} freezes no flows — nothing compared"

    # ⚠ The advice still branches, and the reason changed rather than went away. Both
    # cases are staleness now (slices 6 and 7), so the shared half is one message — but
    # the station's dump mirrors five registry-selection judgement calls by hand, and a
    # mis-mirrored one reads exactly like a reference move while being neither. That
    # question has to be asked FIRST on this case and is meaningless on the other, and
    # after slice 7 a wrong answer to it gets *written into* the frozen manifest by the
    # regeneration this message sends you to. Kept per slice 5's lesson that no test
    # catches a correct assertion giving wrong advice.
    biosphere = manifest_name.startswith("biosphere")
    ceremony = (
        "docs/biosphere-reference.md" if biosphere else "docs/station-reference.md"
    )
    # ⚠ The two contracts regenerate differently since slice C7, and the branch is the
    # slice's own progress showing through: the biosphere manifest is written by the
    # reference, the station's is still written by the checker. When the station writer
    # lands this collapses back to one string — and until it does, printing the wrong
    # command is exactly the "correct assertion, wrong advice" failure slice 5 recorded.
    regen = (
        "cd rust && cargo run --example dump_biosphere_inventory -- --write-manifest"
        if biosphere
        else "uv run python tests/test_station_freeze_manifest.py"
    )
    selection = (
        ""
        if biosphere
        else (
            "⚠ FIRST, before reading this as a reference move at all: check the "
            "registry SELECTION in the dump example against the Python gate's "
            "`_station_registries()`. A mis-mirrored build option (self-discharge, "
            "with_harvest, the fast-vs-slow registry index) reads exactly like a "
            "reference change and is not one — and since slice 7 regenerating would "
            "write it into the frozen manifest. Only if the selection is right:\n"
        )
    )
    advice = (
        f"{selection}⚠ This manifest is generated FROM this dump, so this is NOT a "
        "port-vs-port divergence: the reference tree has changed and the committed "
        f"manifest has not been regenerated. That is an unfreeze — follow the ceremony "
        f"in {ceremony}, then `{regen}`. If you did not mean to change "
        "the frozen surface, the finding is whatever added or removed the name."
    )
    for axis in sorted(_COMPARED_AXES):
        assert dump[axis] == manifest[axis], (
            f"{label} {axis} diverges between the Rust tree and {manifest_name}:\n"
            f"  only in Rust:     {sorted(set(dump[axis]) - set(manifest[axis]))}\n"
            f"  only in manifest: {sorted(set(manifest[axis]) - set(dump[axis]))}\n"
            f"{advice}"
        )

    # ⚠ The mapping axes report the ROSTER difference and the CHANGED-VALUE difference
    # separately, because they are different findings with different first questions: a
    # name only in Rust is a loader added, a name only in the manifest is a loader
    # dropped, and a name in both with a different digest is a param FILE edited without
    # the ceremony.
    #
    # ⚠⚠ This loop is here because TWO NEGATIVE CONTROLS FOUND IT MISSING. Slice C8's
    # first draft added `_COMPARED_MAPPINGS` and no consumer for it — a constant that
    # read exactly like coverage. `test_the_dump_key_sets_are_the_ones_the_generators_
    # consume` stayed green (it checks key sets, not comparisons), ruff does not flag an
    # unused module-level name, and the suite was green. What said so was editing a
    # param file without regenerating, and removing newline normalization from the
    # reference: both left this gate **passing**. *A roster with no consumer is the
    # `docs/log/reference-flip.md` slice-8 lesson exactly — a control with no test to
    # redden IS the finding — and here the control had to be run to see it.*
    for axis in sorted(_COMPARED_MAPPINGS):
        assert axis in manifest, f"{manifest_name} has no {axis} to compare"
        rust, frozen = dump[axis], manifest[axis]
        changed = sorted(k for k in set(rust) & set(frozen) if rust[k] != frozen[k])
        assert rust == frozen, (
            f"{label} {axis} diverges between the Rust tree and {manifest_name}:\n"
            f"  only in Rust (loaded, not frozen):     "
            f"{sorted(set(rust) - set(frozen))}\n"
            f"  only in manifest (frozen, not loaded): "
            f"{sorted(set(frozen) - set(rust))}\n"
            f"  same name, different digest:           {changed}\n"
            f"{advice}"
        )
        # ⚠ And guard the comparison, not just its result: an empty mapping on both
        # sides is a green test that has checked nothing.
        assert frozen, f"{manifest_name} freezes no {axis} — nothing compared"

    # ⚠ The census axes. Written with an `axis in dump` guard while only the biosphere
    # carried a Rust-authored census, so that C4b would start comparing the station's
    # without this file being edited. C4b landed and the guard was REMOVED rather than
    # left: with both dumps carrying a census it can never fire, and a `continue` that
    # cannot fire is a `continue` that silently skips the comparison the day a dump
    # stops emitting one. That case is not unguarded — `set(dump) == dump_keys` above
    # reddens on a missing key — so the guard bought nothing and could only hide.
    for axis in sorted(_COMPARED_CENSUS):
        assert axis in dump, f"{label} dump emits no {axis} to compare"
        frozen_nonempty = {k: v for k, v in manifest[axis].items() if v}
        assert frozen_nonempty, f"{manifest_name} freezes no {axis} — nothing compared"
        changed = sorted(
            k
            for k in set(dump[axis]) & set(frozen_nonempty)
            if dump[axis][k] != frozen_nonempty[k]
        )
        assert dump[axis] == frozen_nonempty, (
            f"{label} {axis} diverges between the Rust tree and {manifest_name}:\n"
            f"  only in Rust (declared, not frozen):     "
            f"{sorted(set(dump[axis]) - set(frozen_nonempty))}\n"
            f"  only in manifest (frozen, not declared): "
            f"{sorted(set(frozen_nonempty) - set(dump[axis]))}\n"
            f"  same scenario, different claims:         {changed}\n"
            f"{advice}"
        )


@pytest.mark.skipif(shutil.which("cargo") is None, reason="cargo not installed")
def test_the_frozen_biosphere_manifest_is_not_stale() -> None:
    """Every biosphere key sourced from the reference tree still reads what it emits.

    The set axes are covered above; this is the rest of what slice 6 re-anchored — the
    horizons and the light-path fingerprint — so a reference-side change to any of them
    is red rather than a manifest quietly describing a tree that has moved on.

    ⚠ The fingerprint is hashed here rather than compared sample by sample, because the
    hash is what the manifest stores and hashing is the one step the Rust side does not
    do (that crate carries no digest dependency). The samples themselves are exact
    hex-float text, so this is an exact comparison, not a tolerance.
    """
    manifest = json.loads(
        (DOCS_DIR / "biosphere-reference.manifest.json").read_text(encoding="utf-8")
    )
    dump = _rust_inventory(RUST_DOMAINS_DIR, "dump_biosphere_inventory")

    fingerprint = hashlib.sha256(
        "|".join(dump["light_path_samples"]).encode("utf-8")
    ).hexdigest()
    assert manifest["forcing"]["light_path"] == fingerprint, (
        "the reference tree's within-day PAR shape has moved and the manifest still "
        "pins the old fingerprint — an unfreeze, not a diff to accept"
    )
    assert dump["light_path_samples"], "no samples compared"

    assert manifest["long_horizon_years"] == dump["horizons"]["long_horizon_years"]
    frozen_years = {
        name: entry["years"] for name, entry in manifest["scenarios"].items()
    }
    for key, years in dump["horizons"].items():
        assert years in frozen_years.values(), (
            f"the reference tree's {key} = {years} appears in no frozen scenario: "
            f"{frozen_years}"
        )


