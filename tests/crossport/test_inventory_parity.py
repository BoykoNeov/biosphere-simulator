"""Reference flip: the Rust tree's own inventory vs. the frozen manifests.

⚠⚠ **BOTH CASES ARE NOW STALENESS CHECKS, AND THAT IS THE FIRST THING TO KNOW BEFORE
READING A FAILURE.** Slice 3 built both as *parity* checks with two independent origins.
Slice 6 re-anchored the **biosphere** manifest to the Rust tree and slice 7 the
**station** one, so for both:

* **a STALENESS check.** The manifest is generated from the same derivations this dump
  prints — since slice C7 the biosphere's is written by the reference itself, the
  station's still by the checker — so a disagreement no longer means "the
  ports differ" — it means **the committed manifest is out of date with the reference
  tree**, i.e. something was added to the reference and never frozen. That is the
  completeness axis, re-homed to the side that now owns it. Python's conformance to the
  same sets is checked separately and cargo-free, in `tests/test_freeze_manifest.py` and
  `tests/test_station_freeze_manifest.py`.

**Why these are still worth running, and are not round trips.** Each compares the
*committed artifact* against a *freshly built tree* — the same relationship the Python
completeness gates always had, on the other side. What they can no longer do is
arbitrate between the ports; that authority went with the flip.

⚠ **The station's failure advice keeps its own paragraph, and it matters MORE now, not
less.** The dump's registry selection is five hand-mirrored judgement calls
(`dump_station_inventory.rs` lists them), and after slice 7 a mis-mirrored one is
**written into the frozen manifest** by a regeneration rather than merely reported as a
mismatch. So the first question on a station failure is still "is the selection right?",
though the second changed from "which port is wrong?" to "what moved in the reference,
and was it meant to?".

⚠⚠ **The manifests' third axis, `param_files`, IS compared — since slice C8, and for
three slices before that it deliberately was not.** The reversal is kept in full,
because the old reason was correct for its day and the new one is narrower than it
looks.

*Until C1:* the port read no YAML at all. It read `biosphere_params.txt` /
`sibling_params.txt` / `station_params.txt`, all three **generated by Python**
(`tests/crossport/gen_*_params.py`) from the frozen loaders, as flat `name → hexfloat`
lines whose prefixes were the generator's naming and not filenames — `photo.` against
`photosynthesis.yaml`, three prefixes out of the single `phenology.yaml`, 17 loaders
against 15 frozen files, and no prefix at all on the sibling/station side. Anything Rust
printed under that key would have been the Python list travelling out and back, so the
gate would have compared Python against Python: the self-referential shape this repo had
to dissolve once already, for the RNG vectors.

*Since C1 and C8:* the reference loads the YAML itself and produces the census and the
digest, so the key has a referent. ⚠ **But what re-anchored is the census RULE and the
normalization RULE, not the numbers** — the 23 digits are author-neutral by
construction, because both sides hash the same file the same way. So what this
comparison actually watches is the **roster**: a param file the reference stopped
loading, or one added and
wired into no loader. It is compared as a whole mapping rather than as a key set, which
is what additionally catches an *edited* param file whose manifest entry was never
regenerated — the desync slice 5 measured, on the param axis.

⚠ **The authoring contract joined in slice 8, and it is a THIRD kind of case.** Its
surface is the author-facing *platform* (grammar, VM node/op set, file schema, flow-type
registry), which has no built registry to walk — so unlike the two above, the reference
side cannot enumerate it at runtime and every axis is part derived, part hand-maintained
roster. `authoring::surface`'s module docs and that manifest's `_authority` block say
which is which per key. The staleness check is the same in shape and weaker in evidence,
and it is written down here so nobody reads a green authoring row as the station row's
equal.
"""

